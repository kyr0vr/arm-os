"""Bake the ArmOS Mono bitmap font into kernel/font.dull.

ArmOS Mono is Cascadia Mono / Cascadia Code (SIL Open Font License 1.1, see fonts/)
rendered once at the sizes the boot screen and the apps use. The OFL reserves the name
"Cascadia Code", so the baked version carries its own name.

Each glyph is a cell `advance` pixels wide (padded to an even width) and `height`
tall, top row first; pixels are 4-bit coverage, two per byte, low nibble first.

    python tools/make_font.py      (needs Pillow and the Cascadia fonts, as on Windows 11)
"""

import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = "C:/Windows/Fonts"
FIRST, COUNT = 32, 95


def bake(path, size, bold=False):
    f = ImageFont.truetype(os.path.join(FONTS, path), size)
    if bold:
        f.set_variation_by_name("Bold")
    advance = int(round(f.getlength("M")))
    ascent, descent = f.getmetrics()
    height = ascent + descent
    width = advance + (advance & 1)
    data = bytearray()
    for code in range(FIRST, FIRST + COUNT):
        img = Image.new("L", (width, height), 0)
        ImageDraw.Draw(img).text((0, 0), chr(code), font=f, fill=255)
        px = img.load()
        for y in range(height):
            for x in range(0, width, 2):
                a = (px[x, y] + 8) // 17
                b = (px[x + 1, y] + 8) // 17
                data.append(min(a, 15) | (min(b, 15) << 4))
    return advance, height, width // 2, bytes(data)


def array(name, data):
    lines = [f"fixed {name} [{len(data)}] u8 = ["]
    for i in range(0, len(data), 32):
        chunk = ", ".join(str(b) for b in data[i:i + 32])
        lines.append("    " + chunk + ("," if i + 32 < len(data) else "]"))
    return "\n".join(lines)


def main():
    reg = bake("CascadiaMono.ttf", 25)
    bold = bake("CascadiaCode.ttf", 25, bold=True)
    small = bake("CascadiaMono.ttf", 22)
    large = bake("CascadiaCode.ttf", 46, bold=True)
    assert reg[:3] == bold[:3]
    out = [
        "-- ArmOS Mono: bitmap font baked from Cascadia Mono and Cascadia Code",
        "-- (Copyright Microsoft Corporation; SIL Open Font License 1.1 - see fonts/).",
        "-- Generated by tools/make_font.py - do not edit.",
        "",
        "fixed first u8 = 32",
        "fixed glyphs u8 = 95",
        f"fixed advance u32 = {reg[0]}         -- regular and bold, 25 px",
        f"fixed height u32 = {reg[1]}",
        f"fixed stride u64 = {reg[2]}           -- bytes per glyph row",
        f"fixed small_advance u32 = {small[0]}   -- regular, 22 px",
        f"fixed small_height u32 = {small[1]}",
        f"fixed small_stride u64 = {small[2]}",
        f"fixed large_advance u32 = {large[0]}   -- bold, 46 px (titles)",
        f"fixed large_height u32 = {large[1]}",
        f"fixed large_stride u64 = {large[2]}",
        "",
        array("regular", reg[3]),
        "",
        array("bold", bold[3]),
        "",
        array("small", small[3]),
        "",
        array("large", large[3]),
        "",
    ]
    path = os.path.join(ROOT, "kernel", "font.dull")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {path}: 25 px {reg[0]}x{reg[1]}, 22 px {small[0]}x{small[1]}, "
          f"46 px {large[0]}x{large[1]}, {len(reg[3]) + len(bold[3]) + len(small[3]) + len(large[3])} bytes of glyphs")


if __name__ == "__main__":
    main()
