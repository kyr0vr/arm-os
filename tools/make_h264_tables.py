"""Generate lib/h264tables.dull: the constant tables of the H.264 decoder.

They come from OpenH264 (tools/h264_openh264_tables.json, BSD 2-clause; its license
is repeated in the generated file), plus the 4x4 and 8x8 normAdjust values from the
H.264 standard (the 8x8 ones are checked against OpenH264's matrix).

    python tools/make_h264_tables.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, "tools", "h264_openh264_tables.json")))

V4 = [[10, 16, 13], [11, 18, 14], [13, 20, 16], [14, 23, 18], [16, 25, 20], [18, 29, 23]]
V8 = [[20, 18, 32, 19, 25, 24], [22, 19, 35, 21, 28, 26], [26, 23, 42, 24, 33, 31],
      [28, 25, 45, 26, 35, 33], [32, 28, 51, 30, 40, 38], [36, 32, 58, 34, 46, 43]]


def norm4(m, r):
    i, j = r // 4, r % 4
    if i % 2 == 0 and j % 2 == 0:
        return V4[m][0]
    if i % 2 == 1 and j % 2 == 1:
        return V4[m][1]
    return V4[m][2]


def norm8(m, r):
    i, j = r // 8, r % 8
    if i % 4 == 0 and j % 4 == 0:
        return V8[m][0]
    if i % 2 == 1 and j % 2 == 1:
        return V8[m][1]
    if i % 4 == 2 and j % 4 == 2:
        return V8[m][2]
    if (i % 4 == 0 and j % 2 == 1) or (i % 2 == 1 and j % 4 == 0):
        return V8[m][3]
    if (i % 4 == 0 and j % 4 == 2) or (i % 4 == 2 and j % 4 == 0):
        return V8[m][4]
    return V8[m][5]


def array(name, kind, values, per_line=16):
    lines = [f"fixed {name} [{len(values)}] {kind} = ["]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(str(v) for v in values[i:i + per_line])
        lines.append("    " + chunk + ("," if i + per_line < len(values) else "]"))
    return "\n".join(lines)


def main():
    n4 = [norm4(m, r) for m in range(6) for r in range(16)]
    n8 = [norm8(m, r) for m in range(6) for r in range(64)]
    assert n8 == T["matrix_v"], "normAdjust8x8 does not match OpenH264"
    license_lines = ["-- " + line if line else "--" for line in T["_license"].strip().splitlines()]
    out = [
        "-- Tables for the H.264 decoder. Generated by tools/make_h264_tables.py - do not edit.",
        "--",
        "-- From OpenH264 (https://github.com/cisco/openh264): the CABAC context",
        "-- initialization values, rangeTabLPS, the state transitions, the chroma QP table,",
        "-- the default scaling lists, the zigzag scans, the 8x8 significance maps and the",
        "-- deblocking tables. OpenH264's license:",
        "--",
        *license_lines,
        "",
        "-- CABAC: (m, n) for each of the 460 contexts and the 4 init types (I, then",
        "-- cabac_init_idc 0-2): [(ctx * 4 + type) * 2 + 0 or 1]",
        array("ctx_init", "i8", T["ctx"], 24),
        "",
        "-- rangeTabLPS[state * 4 + (range >> 6 & 3)]",
        array("range_lps", "u8", T["range_lps"]),
        "",
        "-- next state after an LPS [state * 2] or an MPS [state * 2 + 1]",
        array("next_state", "u8", T["trans"]),
        "",
        array("chroma_qp", "u8", T["chroma_qp"]),
        "",
        "-- default scaling lists: intra, inter (4x4 then 8x8), raster order",
        array("default4", "u8", T["scaling4_default"]),
        "",
        array("default8", "u8", T["scaling8_default"]),
        "",
        "-- normAdjust (LevelScale without the scaling list) [qp % 6 * 16 + raster], [qp % 6 * 64 + raster]",
        array("norm4", "u8", n4),
        "",
        array("norm8", "u8", n8),
        "",
        "-- scans: scan position -> raster position",
        array("zigzag4", "u8", T["zigzag4"]),
        "",
        array("zigzag8", "u8", T["zigzag8"]),
        "",
        "-- 8x8 blocks: context increments of significant / last flags by scan position",
        array("sig8", "u8", T["sig8"]),
        "",
        array("last8", "u8", T["last8"]),
        "",
        "-- deblocking, indexed by indexA / indexB + 12; tc0 by [(indexA + 12) * 4 + bS]",
        array("alpha", "u8", T["alpha"]),
        "",
        array("beta", "u8", T["beta"]),
        "",
        array("tc0", "i8", T["tc0"]),
        "",
    ]
    path = os.path.join(ROOT, "lib", "h264tables.dull")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
