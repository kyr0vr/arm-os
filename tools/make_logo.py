"""Generate kernel/logo.dull: the ArmOS mark as text art for the boot screen.

The mark is an A with an arrow (DULL's `->`) shot through it. Each row has its
characters and, beside them, what each one is: p = the A (putty), a = the arrow
(amber), space = empty. The arrow doubles as the boot progress bar.

    python tools/make_logo.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ROWS = 17
BAR = (9, 10)          # the two shaft rows
GAP = (8, 11)          # the slot cut around the shaft
LEG = 7                # leg width in characters
APEX = 22              # left column of the left leg on row 0
SPLAY = 1              # columns the legs spread per row


def build():
    width = 60
    grid = [[(" ", " ")] * width for _ in range(ROWS)]

    def put(r, c, k, ch):
        grid[r][c] = (k, ch)

    for r in range(ROWS):
        if r in BAR or r in GAP:
            continue
        left = APEX - r * SPLAY
        right = APEX + 3 + r * SPLAY
        cells = set(range(left, left + LEG)) | set(range(right, right + LEG))
        for c in sorted(cells):
            if c == left:
                ch = "/"
            elif c == right + LEG - 1:
                ch = "\\"
            elif c == left + LEG - 1 and c + 1 not in cells:
                ch = "/"
            elif c == right and c - 1 not in cells:
                ch = "\\"
            else:
                ch = "#"
            put(r, c, "p", ch)
        if r == 0:   # flat cap on the apex
            for c in range(left + 1, right + LEG - 1):
                put(r, c, "p", "#")
    shaft_end = APEX + 3 + BAR[1] * SPLAY + LEG + 7
    for r in BAR:
        for c in range(0, shaft_end):
            put(r, c, "a", "=")
    head = [(BAR[0] - 3, "|\\"), (BAR[0] - 2, "|##\\"), (BAR[0] - 1, "|####\\"), (BAR[0], "|######\\"),
            (BAR[1], "|######/"), (BAR[1] + 1, "|####/"), (BAR[1] + 2, "|##/"), (BAR[1] + 3, "|/")]
    for r, s in head:
        for i, ch in enumerate(s):
            put(r, shaft_end + i, "a", "#" if ch == "|" else ch)
    used = [c for c in range(width) if any(row[c][1] != " " for row in grid)]
    hi = max(used)
    return [row[:hi + 1] for row in grid]


def dull_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    grid = build()
    rows, cols = len(grid), len(grid[0])
    arrow_cols = [c for row in grid for c, (k, _) in enumerate(row) if k == "a"]
    chars = ["".join(ch for _, ch in row) for row in grid]
    kinds = ["".join(k for k, _ in row) for row in grid]
    out = [
        "-- The ArmOS mark as text art: an A with an arrow (DULL's `->`) shot through it.",
        "-- Generated by tools/make_logo.py - do not edit.",
        "",
        f"fixed rows u32 = {rows}",
        f"fixed cols u32 = {cols}",
        f"fixed arrow_first u32 = {min(arrow_cols)}   -- first and last columns of the arrow",
        f"fixed arrow_last u32 = {max(arrow_cols)}",
        "",
        "-- the characters, row by row",
        f"fixed chars [{rows}] string = [",
    ]
    out += ["    " + dull_string(s) + ("," if i < rows - 1 else "]") for i, s in enumerate(chars)]
    out += ["", "-- what each character is: p = the A, a = the arrow, space = nothing",
            f"fixed kinds [{rows}] string = ["]
    out += ["    " + dull_string(s) + ("," if i < rows - 1 else "]") for i, s in enumerate(kinds)]
    out.append("")
    path = os.path.join(ROOT, "kernel", "logo.dull")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {path}: {rows} x {cols}")
    print("\n".join(chars))


if __name__ == "__main__":
    main()
